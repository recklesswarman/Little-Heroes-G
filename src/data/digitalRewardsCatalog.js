SEED_2026_ITEMS.forEach((seed) => {
  if (!DIGITAL_REWARDS_CATALOG.some((i) => i.id === seed.id)) DIGITAL_REWARDS_CATALOG.push(seed);
});

export function getDigitalRewardById(id) {
  return DIGITAL_REWARDS_CATALOG.find(item => item.id === id) || null;
}

export function getAllRewardsByCategory(category) {
  const norm = (category || '').toLowerCase();
  return DIGITAL_REWARDS_CATALOG.filter(item => {
    const itemCat = (item.category || '').toLowerCase();
    if (norm === 'all') return true;
    if (norm === 'weapons' || norm === 'weapon') return itemCat === 'weapons';
    if (norm === 'avatar_gear' || norm === 'avatar gear' || norm === 'gear') return itemCat === 'avatar gear';
    if (norm === 'pet_gear' || norm === 'pet gear') return itemCat === 'pet gear';
    if (norm === 'accessories' || norm === 'accessory') return itemCat === 'accessories';
    if (norm === 'badges' || norm === 'badge') return itemCat === 'badges';
    if (norm === 'trophies' || norm === 'trophy') return itemCat === 'trophies';
    if (norm === 'stickers' || norm === 'sticker') return itemCat === 'stickers';
    if (norm === 'loot') return itemCat === 'loot';
    if (norm === 'snacks' || norm === 'food') return itemCat === 'snacks';
    return itemCat === norm;
  });
}
